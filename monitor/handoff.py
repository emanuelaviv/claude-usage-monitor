"""Build the prompt that starts a new conversation, from the old one's transcript, with no model calls.

Usage:
  python -m monitor.handoff                                 # the most recent Code conversation
  python -m monitor.handoff --session 1a2b3c4d              # a given conversation (id prefix)
  python -m monitor.handoff --next "please follow PROMPT_x.md"   # you are about to start a new packet

Two shapes:
- New packet (with --next, or when the last prompt named a packet): your own prompt, plus a short preamble.
  The preamble gives the project, the branch, the packet file, the files its header says to read first, and
  any reports the old conversation wrote.
- Resume (otherwise): where the old conversation stopped. That is its last message (trimmed), its plan, the
  files it changed, its last build or test result, and the questions it left open.

Everything comes from the transcript and the files on disk; nothing is generated by a model. Paste the result
into a new conversation, check it, and send it. The text is written to data/handoffs/ on this machine only.
"""
import argparse
import json
import os
import re
from datetime import datetime

from .ingest import CODE_ROOT, _STEM, _human_text, _kind
from .packets import find_packet

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_EDIT_TOOLS = {"Edit", "MultiEdit", "Write", "NotebookEdit"}
_SHELL_TOOLS = {"Bash", "PowerShell"}
_CHECK = re.compile(r"\b(pytest|unittest|gradlew|jest|vitest|flutter test|deno test|cargo test|go test|npm (run )?"
                    r"(test|build|lint)|pnpm (test|build)|yarn (test|build)|tsc\b|assemble\w*|lint\w*|"
                    r"python -m monitor\.\w+)", re.I)
_PATHLIKE = re.compile(r"[\w./\\-]*[\w-]\.(?:md|txt|json|ya?ml|py|kt|kts|ts|tsx|js|sql|gradle|csv)\b")


def _main_file(session_prefix=None):
    best = None
    for dp, dn, fns in os.walk(CODE_ROOT):
        for fn in fns:
            if not fn.endswith(".jsonl") or fn == "journal.jsonl":
                continue
            path = os.path.join(dp, fn)
            if _kind(path) != "main":
                continue
            if session_prefix and not fn.startswith(session_prefix):
                continue
            m = os.path.getmtime(path)
            if best is None or m > best[0]:
                best = (m, path)
    return best[1] if best else None


def _read_first(packet_path):
    """Files the packet's header lists under a 'read first' heading (up to 12)."""
    try:
        lines = open(packet_path, encoding="utf-8", errors="replace").read().splitlines()[:80]
    except OSError:
        return []
    out, on = [], False
    for ln in lines:
        if re.search(r"read (these )?first|before you start, read|read before", ln, re.I):
            on = True
            continue
        if on:
            if not ln.strip() or ln.lstrip().startswith("#"):
                if out:
                    break
                continue
            for item in _PATHLIKE.findall(ln):
                if item not in out and len(out) < 12:
                    out.append(item)
    return out


def _apply_plan(plan, inp):
    """Follow the task-list tool's updates so the last state is known."""
    if isinstance(inp.get("items"), list):
        return [{"content": i.get("content", ""), "status": i.get("status", "pending")} for i in inp["items"]]
    if inp.get("advance"):
        for i, it in enumerate(plan):
            if it["status"] == "in_progress":
                it["status"] = "completed"
                nxt = next((j for j in range(i + 1, len(plan)) if plan[j]["status"] == "pending"), None)
                if nxt is not None:
                    plan[nxt]["status"] = "in_progress"
                break
    for n in inp.get("done") or []:
        if 0 < n <= len(plan):
            plan[n - 1]["status"] = "completed"
    if inp.get("start") and 0 < inp["start"] <= len(plan):
        plan[inp["start"] - 1]["status"] = "in_progress"
    return plan


def read_transcript(path):
    """What a handoff needs from one main transcript."""
    facts = {"title": None, "cwd": None, "branch": None, "stems": [], "edits": {}, "created": [],
             "checks": [], "plan": [], "last_text": "", "context": 0, "last_ts": None, "prompts": 0,
             "first_prompt": "", "recap": "", "ask": ""}
    pending_checks, last_msg_id, texts = {}, None, []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            try:
                d = json.loads(line)
            except ValueError:
                continue
            t = d.get("type")
            facts["cwd"] = d.get("cwd") or facts["cwd"]
            facts["branch"] = d.get("gitBranch") or facts["branch"]
            if t == "custom-title" and d.get("customTitle"):
                facts["title"] = d["customTitle"]
            elif t == "ai-title" and d.get("aiTitle") and not facts["title"]:
                facts["title"] = d["aiTitle"]
            elif t == "user":
                text = _human_text(d)
                if text is not None:
                    facts["prompts"] += 1
                    if not facts["first_prompt"]:
                        facts["first_prompt"] = text
                    for m in _STEM.finditer(text):
                        facts["stems"].append(m.group(1))
                    texts, last_msg_id = [], None
                content = (d.get("message") or {}).get("content")
                if isinstance(content, list):
                    for b in content:
                        if isinstance(b, dict) and b.get("type") == "tool_result" and b.get("tool_use_id") in pending_checks:
                            cmd, ts = pending_checks.pop(b["tool_use_id"])
                            facts["checks"].append((cmd, not b.get("is_error"), ts))
            elif t == "assistant" and not d.get("isSidechain"):
                m = d.get("message") or {}
                u = m.get("usage") or {}
                ctx = (u.get("input_tokens") or 0) + (u.get("cache_read_input_tokens") or 0) + \
                      (u.get("cache_creation_input_tokens") or 0) + (u.get("output_tokens") or 0)
                if ctx:
                    facts["context"] = ctx
                facts["last_ts"] = d.get("timestamp") or facts["last_ts"]
                for b in m.get("content") or []:
                    if not isinstance(b, dict):
                        continue
                    if b.get("type") == "text" and b.get("text", "").strip():
                        if m.get("id") != last_msg_id:
                            texts, last_msg_id = [], m.get("id")
                        texts.append(b["text"])
                        facts["last_text"] = "\n".join(texts)
                    elif b.get("type") == "tool_use":
                        name, inp = b.get("name", ""), b.get("input") or {}
                        if name in _EDIT_TOOLS and inp.get("file_path"):
                            fp = inp["file_path"]
                            facts["edits"][fp] = facts["edits"].get(fp, 0) + 1
                            if name == "Write" and fp not in facts["created"]:
                                facts["created"].append(fp)
                        elif name in _SHELL_TOOLS and _CHECK.search(inp.get("command", "") or ""):
                            pending_checks[b.get("id")] = (inp["command"].strip().splitlines()[0][:120], d.get("timestamp"))
                        elif name.endswith("update_plan"):
                            facts["plan"] = _apply_plan(facts["plan"], inp)
                        elif name.endswith("wrap_up"):           # wrapping up closes the task list
                            facts["plan"] = [{**i, "status": "completed"} for i in facts["plan"]]
                            facts["recap"] = str(inp.get("recap") or "")
                            facts["ask"] = str(inp.get("ask") or "").strip()
                        elif name == "TodoWrite" and isinstance(inp.get("todos"), list):
                            facts["plan"] = [{"content": x.get("content", ""), "status": x.get("status", "pending")}
                                             for x in inp["todos"]]
    return facts


def _trim(text, limit=1500):
    text = re.sub(r"\n{3,}", "\n\n", text.strip())
    if len(text) <= limit:
        return text
    cut = text[:limit]
    return cut[:cut.rfind("\n") if cut.rfind("\n") > limit * 0.6 else limit].rstrip() + "\n[…trimmed]"


def build_prompt(facts, next_prompt=None, path=None):
    loc = lambda iso: datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone().strftime("%b %d %H:%M") if iso else "?"
    title = facts["title"] or "the previous conversation"
    head = [f"New conversation, continuing from “{title}” (last reply {loc(facts['last_ts'])}, "
            f"{facts['context'] / 1000:.0f}K tokens). It was moved here so that context isn't resent on every message."]
    branch = facts["branch"] if facts["branch"] not in (None, "", "HEAD") else None
    proj = f"Project: `{facts['cwd']}`" + (f" · branch `{branch}`" if branch else "")

    def rel(f):
        cwd = facts["cwd"] or ""
        return os.path.relpath(f, cwd) if cwd and os.path.normcase(f).startswith(os.path.normcase(cwd)) else f
    next_stem = None
    if next_prompt:
        m = _STEM.search(next_prompt)
        next_stem = m.group(1) if m else None
    stem = next_stem or (facts["stems"][-1] if facts["stems"] else None)
    packet = find_packet(stem, facts["cwd"]) if stem else None
    lines = head + ["", proj]
    if packet:
        lines.append(f"Packet: `{packet}`. Read it first.")
        rf = _read_first(packet)
        if rf:
            lines.append("Its header also says to read: " + ", ".join(f"`{x}`" for x in rf) + ".")
    reports = [f for f in facts["created"] if f.lower().endswith((".md", ".txt"))][-5:]
    if next_prompt:            # a new packet: the user's own prompt carries the task
        if reports:
            lines.append("Reports the previous conversation wrote, in case they matter: "
                         + ", ".join(f"`{rel(x)}`" for x in reports) + ".")
        lines += ["", next_prompt.strip()]
        return "\n".join(lines)
    if facts["first_prompt"]:
        lines += ["", "The original request (its first message, trimmed):", ""]
        lines += ["> " + ln if ln.strip() else ">" for ln in _trim(facts["first_prompt"], 700).splitlines()]
    lines += ["", "Where the previous conversation stopped (its last message, trimmed):", ""]
    lines += ["> " + ln if ln.strip() else ">" for ln in _trim(facts["last_text"]).splitlines()]
    if facts.get("recap") and facts["recap"][:40] not in facts["last_text"]:
        lines += ["", f"Its last recap: {facts['recap'].strip()}"]
    if facts.get("ask"):
        lines.append(f"It had asked me: {facts['ask']}")
    plan = facts["plan"]
    if plan:
        mark = {"completed": "done", "in_progress": "in progress", "pending": "to do"}
        lines += ["", "Its task list at that point:"]
        lines += [f"- [{mark.get(i['status'], i['status'])}] {i['content']}" for i in plan]
    if facts["edits"]:
        changed = list(facts["edits"])[-12:]
        lines += ["", "Files it changed (most recent last): " + ", ".join(f"`{rel(x)}`" for x in changed)
                  + (f" (+{len(facts['edits']) - 12} more)" if len(facts["edits"]) > 12 else "") + "."]
    if facts["checks"]:
        cmd, ok, ts = facts["checks"][-1]
        lines.append(f"Last build or test: `{cmd}`: {'passed' if ok else 'FAILED'} ({loc(ts)}).")
    plain = re.sub(r"[*_`]+", "", facts["last_text"])
    qs = []
    for found in re.findall(r"[^.!?\n]*\?", plain):
        found = found.strip(" -:")
        if len(found) > 15 and found not in qs:
            qs.append(found)
    qs = qs[-4:]
    if qs:
        lines += ["", "Questions it left open:"] + [f"- {q}" for q in qs]
    lines += ["", "Before you continue: re-read the packet and the changed files above. Don't assume anything that "
                  "isn't written here, and ask me if something is unclear. Then pick up from the task list."]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--session", help="session id or prefix (default: the most recent Code conversation)")
    ap.add_argument("--next", dest="next_prompt", help="the prompt you are about to send, if it starts a new packet")
    ap.add_argument("--quiet", action="store_true", help="only write the file, don't print the prompt")
    a = ap.parse_args()
    path = _main_file(a.session)
    if not path:
        raise SystemExit("No matching Code conversation found.")
    facts = read_transcript(path)
    text = build_prompt(facts, a.next_prompt, path)
    os.makedirs(os.path.join(HERE, "data", "handoffs"), exist_ok=True)
    out = os.path.join(HERE, "data", "handoffs",
                       f"{os.path.basename(path)[:8]}-{datetime.now().strftime('%Y%m%d-%H%M')}.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(text + "\n")
    if not a.quiet:
        print(text)
    print(f"\n[{len(text)} characters, about {len(text) // 4} tokens. Saved to {out}]")


if __name__ == "__main__":
    main()
